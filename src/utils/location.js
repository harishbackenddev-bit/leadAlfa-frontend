/** Select value when the brand enters a city not in the list. */
export const CITY_OTHER_VALUE = "__other__";

const brandCityByValue = new Map();
for (const cities of Object.values(creatorCitiesByProvince)) {
  for (const city of cities) {
    brandCityByValue.set(city.value, city);
  }
}

export const brandCityOptions = [
  ...[...brandCityByValue.values()].sort((a, b) =>
    a.label.localeCompare(b.label)
  ),
  { label: "Other", value: CITY_OTHER_VALUE },
];

export function resolveBrandCityValue(city, cityOther) {
  if (city === CITY_OTHER_VALUE) {
    return (cityOther || "").trim();
  }
  return (city || "").trim();
}

/** Restore city + cityOther from a saved city string (e.g. after draft reload). */
export function getBrandCityFormDefaults(savedCity = "") {
  const trimmed = (savedCity || "").trim();
  if (!trimmed) {
    return { city: "", cityOther: "" };
  }
  const inList = brandCityOptions.some(
    (option) => option.value !== CITY_OTHER_VALUE && option.value === trimmed
  );
  if (inList) {
    return { city: trimmed, cityOther: "" };
  }
  return { city: CITY_OTHER_VALUE, cityOther: trimmed };
}

